// Writes the tool list in apps/web/content/docs/mcp.md (between the mcp-tools markers) from the operations, so the
// docs list exactly what the MCP server serves. Run after changing an operation's name, description or scope:
//   pnpm --filter @xstate/api docs:mcp          (rewrites the file)
//   pnpm --filter @xstate/api docs:mcp --check  (fails if it is out of date)

import fs from 'node:fs'
import path from 'node:path'
import { operations } from '../src/operations'
import type { McpScope } from '../src/operations/define'

const DOC = path.resolve(import.meta.dirname, '../../web/content/docs/mcp.md')
const START = '<!-- mcp-tools:start (generated by apps/api/scripts/mcp-tools-doc.ts; do not edit) -->'
const END = '<!-- mcp-tools:end -->'

const SECTIONS: { title: string; scopes: McpScope[]; note: string }[] = [
  { title: 'Always', scopes: ['profile'], note: 'Every connection has these.' },
  { title: 'Email', scopes: ['mail.read', 'mail.draft', 'mail.send'], note: 'Read only, Draft only or Draft and send.' },
  { title: 'Calendar', scopes: ['calendar.read', 'calendar.write'], note: 'Read, or Read and change.' },
  { title: 'Storage', scopes: ['storage.read', 'storage.write'], note: 'Read, or Read and change.' },
  { title: 'Contacts', scopes: ['contacts.read', 'contacts.write'], note: 'Read, or Read and change.' },
  { title: 'Setup', scopes: ['setup'], note: 'Only when an owner or admin turns on Manage domains and mailboxes.' },
]

const LEVEL: Record<McpScope, string> = {
  profile: 'always',
  'mail.read': 'read only',
  'mail.draft': 'draft only',
  'mail.send': 'draft and send',
  'calendar.read': 'read',
  'calendar.write': 'read and change',
  'storage.read': 'read',
  'storage.write': 'read and change',
  'contacts.read': 'read',
  'contacts.write': 'read and change',
  setup: 'setup',
}

/** The first sentence of a description: enough for a table, the rest is in the tool itself. */
const first = (text: string) => (text.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? text).replace(/\|/g, '\\|')

function render(): string {
  const parts = [START, '']
  for (const section of SECTIONS) {
    const ops = operations.filter((op) => op.mcp !== false && !op.public && section.scopes.includes(op.mcp.scope))
    parts.push(`### ${section.title}`, '', section.note, '', '| Tool | Needs | What it does |', '| - | - | - |')
    for (const op of ops) {
      const hints = op.mcp === false ? null : op.mcp
      const mark = hints?.destructive ? ' (deletes)' : ''
      parts.push(`| \`${op.name}\` | ${hints ? LEVEL[hints.scope] : ''}${mark} | ${first(op.description)} |`)
    }
    parts.push('')
  }
  parts.push(END)
  return parts.join('\n')
}

const doc = fs.readFileSync(DOC, 'utf8')
const a = doc.indexOf(START)
const b = doc.indexOf(END)
if (a < 0 || b < 0) throw new Error(`${DOC} has no ${START} … ${END} markers`)
const next = doc.slice(0, a) + render() + doc.slice(b + END.length)
if (process.argv.includes('--check')) {
  if (next !== doc) {
    console.error('apps/web/content/docs/mcp.md is out of date: run pnpm --filter @xstate/api docs:mcp')
    process.exit(1)
  }
  console.log('mcp.md tool list is up to date')
} else {
  fs.writeFileSync(DOC, next)
  console.log(`wrote ${operations.filter((op) => op.mcp !== false && !op.public).length} tools to ${path.relative(process.cwd(), DOC)}`)
}
